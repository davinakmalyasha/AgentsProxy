// Command genprojects writes internal/projectsgen/projects_gen.go.
//
// Go cannot discover packages at runtime, so a project's backend and agent
// tools must be imported for their init() registration to run. This
// generator keeps the rule "a new project is one folder": add the folder,
// run `go generate ./...`, and the imports update deterministically. The
// generated package is importable by the server, migrate, and provision
// commands, so every binary sees the same project registrations.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const modulePath = "github.com/davinakmalyasha/agents-proxy"

func main() {
	root, err := os.Getwd()
	if err != nil {
		fail(err)
	}
	root, err = findModuleRoot(root)
	if err != nil {
		fail(err)
	}
	projectsDir := filepath.Join(root, "projects")
	entries, err := os.ReadDir(projectsDir)
	if err != nil {
		fail(err)
	}

	var imports []string
	for _, e := range entries {
		if !e.IsDir() || strings.HasPrefix(e.Name(), "_") {
			continue
		}
		slug := e.Name()
		if hasGoFiles(filepath.Join(projectsDir, slug, "agent", "tools")) {
			imports = append(imports, modulePath+"/projects/"+slug+"/agent/tools")
		}
		backendDir := filepath.Join(projectsDir, slug, "backend")
		subs, err := os.ReadDir(backendDir)
		if err != nil {
			continue
		}
		for _, sub := range subs {
			if !sub.IsDir() || strings.HasPrefix(sub.Name(), "_") || sub.Name() == "testutil" {
				continue
			}
			if hasGoFiles(filepath.Join(backendDir, sub.Name())) {
				imports = append(imports, modulePath+"/projects/"+slug+"/backend/"+sub.Name())
			}
		}
	}
	sort.Strings(imports)

	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./cmd/genprojects; DO NOT EDIT.\n\n")
	b.WriteString("package projectsgen\n\n")
	b.WriteString("import (\n")
	for _, imp := range imports {
		fmt.Fprintf(&b, "\t_ %q\n", imp)
	}
	b.WriteString(")\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	out := filepath.Join(root, "internal", "projectsgen", "projects_gen.go")
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		fail(err)
	}
	if err := os.WriteFile(out, src, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("wrote %s (%d project packages)\n", out, len(imports))
}

func findModuleRoot(start string) (string, error) {
	dir := start
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found above %s", start)
		}
		dir = parent
	}
}

func hasGoFiles(dir string) bool {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false
	}
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".go") && !strings.HasSuffix(e.Name(), "_test.go") {
			return true
		}
	}
	return false
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "genprojects:", err)
	os.Exit(1)
}
