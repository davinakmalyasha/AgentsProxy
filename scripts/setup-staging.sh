#!/usr/bin/env bash
# One-shot staging setup:
#   1. read the staging admin DSN (prompt or .env.staging)
#   2. apply the full embedded migration chain
#   3. generate and set the app_runtime password
#   4. write the staging runtime DSN + a staging admin key to .env.staging
#
# This never touches production. It refuses the production project ref.
set -euo pipefail
cd "$(dirname "$0")/.."

ENV_FILE=".env.staging"
ADMIN_DSN="${DATABASE_ADMIN_URL:-}"

if [ -f "$ENV_FILE" ]; then
    set -a
    # shellcheck disable=SC1091
    . "./$ENV_FILE"
    set +a
    ADMIN_DSN="${DATABASE_ADMIN_URL:-$ADMIN_DSN}"
fi

if [ -z "$ADMIN_DSN" ]; then
    printf 'Paste the staging admin DSN (Supabase 5432, user postgres): '
    # -s hides the input; the DSN is a secret.
    IFS= read -rsp '' ADMIN_DSN
    printf '\n'
fi

case "$ADMIN_DSN" in
    postgres://*|postgresql://*) ;;
    *)
        echo "refusing: DSN must start with postgres:// or postgresql://" >&2
        exit 1
        ;;
esac

case "$ADMIN_DSN" in
    *hwcizjzkqexviegsyaql*)
        echo "refusing: this is the production Supabase project" >&2
        exit 1
        ;;
    *supabase.co*|*pooler.supabase.com*) ;;
    *)
        echo "refusing: not a Supabase host" >&2
        exit 1
        ;;
esac

if ! command -v psql >/dev/null 2>&1; then
    echo "psql is required (Laragon PostgreSQL bin or PostgreSQL client)" >&2
    exit 1
fi
if ! command -v openssl >/dev/null 2>&1; then
    echo "openssl is required" >&2
    exit 1
fi

cat > "$ENV_FILE" <<EOF
# Generated by scripts/setup-staging.sh. Gitignored. Staging only.
ENV=staging
ALLOW_REMOTE_DB=true
DATABASE_URL=$ADMIN_DSN
DATABASE_ADMIN_URL=$ADMIN_DSN
RUN_MIGRATIONS=false
LLM_API_KEY=migrate-unused
ADMIN_API_KEY=migrate-unused
ALLOW_ORIGINS=*
EOF
chmod 600 "$ENV_FILE" 2>/dev/null || true

echo "[staging] applying platform + project migrations"
ENV=staging ALLOW_REMOTE_DB=true \
    DATABASE_URL="$ADMIN_DSN" \
    DATABASE_ADMIN_URL="$ADMIN_DSN" \
    LLM_API_KEY=migrate-unused \
    ADMIN_API_KEY=migrate-unused \
    ALLOW_ORIGINS='*' \
    go run ./cmd/migrate

APP_RUNTIME_PASSWORD="$(openssl rand -hex 24)"
psql "$ADMIN_DSN" -v ON_ERROR_STOP=1 -q \
    -c "ALTER ROLE app_runtime PASSWORD '$APP_RUNTIME_PASSWORD';"

read -r STAGING_REF POOLER_HOST < <(ADMIN_DSN="$ADMIN_DSN" python - <<'PY'
import os
from urllib.parse import urlparse
u = urlparse(os.environ["ADMIN_DSN"])
host = (u.hostname or "")
user = (u.username or "")
ref = ""
if user.startswith("postgres."):
    ref = user.split(".", 1)[1]
elif host.startswith("db."):
    ref = host.split(".")[1]
pooler = host if "pooler.supabase.com" in host else "aws-0-ap-southeast-1.pooler.supabase.com"
print(ref, pooler)
PY
)

if [ -z "$STAGING_REF" ]; then
    printf 'Could not read the project ref from the DSN. Paste the staging project ref: '
    IFS= read -r STAGING_REF
fi

STAGING_ADMIN_KEY="$(openssl rand -hex 32)"
RUNTIME_URL="postgresql://app_runtime.${STAGING_REF}:${APP_RUNTIME_PASSWORD}@${POOLER_HOST}:6543/postgres?pgbouncer=true&sslmode=require"

cat >> "$ENV_FILE" <<EOF

# Runtime DSN for the Vercel staging branch (DATABASE_URL).
STAGING_RUNTIME_URL=$RUNTIME_URL
# Use this as ADMIN_API_KEY on the Vercel staging branch.
STAGING_ADMIN_API_KEY=$STAGING_ADMIN_KEY
EOF

echo
echo "[staging] migrations applied and app_runtime password set."
echo "[staging] wrote:"
echo "  DATABASE_ADMIN_URL   -> $ENV_FILE (same as the admin DSN)"
echo "  STAGING_RUNTIME_URL  -> $ENV_FILE (use as DATABASE_URL in Vercel)"
echo "  STAGING_ADMIN_API_KEY-> $ENV_FILE (use as ADMIN_API_KEY in Vercel)"
echo
echo "Next: create/choose a staging Redis, then add the Vercel Preview"
echo "branch variables for the 'staging' branch (see ops/RUNBOOK-staging.md)."
